CREATE TABLE CATEGORIAS (
    ID          NUMBER(19)         GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE      VARCHAR2(60 CHAR)  NOT NULL,
    DESCRIPCION VARCHAR2(200 CHAR),
    CONSTRAINT PK_CATEGORIAS PRIMARY KEY (ID),
    CONSTRAINT UK_CATEGORIAS_NOMBRE UNIQUE (NOMBRE)
);

CREATE TABLE PRODUCTOS (
    ID                  NUMBER(19)         GENERATED BY DEFAULT AS IDENTITY,
    SKU                 VARCHAR2(30 CHAR)  NOT NULL,
    NOMBRE              VARCHAR2(120 CHAR) NOT NULL,
    DESCRIPCION         VARCHAR2(500 CHAR),
    PRECIO              NUMBER(10)         NOT NULL,
    STOCK               NUMBER(10)         DEFAULT 0 NOT NULL,
    CATEGORIA_ID        NUMBER(19)         NOT NULL,
    ACTIVO              NUMBER(1)          DEFAULT 1 NOT NULL,
    FECHA_CREACION      TIMESTAMP(6)       DEFAULT SYSTIMESTAMP NOT NULL,
    FECHA_ACTUALIZACION TIMESTAMP(6),
    CONSTRAINT PK_PRODUCTOS PRIMARY KEY (ID),
    CONSTRAINT UK_PRODUCTOS_SKU UNIQUE (SKU),
    CONSTRAINT FK_PRODUCTOS_CATEGORIA FOREIGN KEY (CATEGORIA_ID) REFERENCES CATEGORIAS (ID),
    CONSTRAINT CK_PRODUCTOS_PRECIO CHECK (PRECIO > 0),
    CONSTRAINT CK_PRODUCTOS_STOCK CHECK (STOCK >= 0),
    CONSTRAINT CK_PRODUCTOS_ACTIVO CHECK (ACTIVO IN (0, 1))
);

CREATE INDEX IX_PRODUCTOS_CATEGORIA ON PRODUCTOS (CATEGORIA_ID);

